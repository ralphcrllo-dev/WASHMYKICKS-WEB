-- ============================================================================
-- WASHMYKICKS — MIGRATION 01: COMPLETE ERD CORE SCHEMA (26 TABLES)
-- Source of Truth: Uploaded WashMyKicks Entity-Relationship Diagram (ERD)
-- Database: Supabase PostgreSQL
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ============================================================================
-- MODULE 1 & 2 CORE LOOKUP TABLES: ROLES & BRANCHES
-- ============================================================================

-- 1. ROLES
CREATE TABLE IF NOT EXISTS public.roles (
  role_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(30) NOT NULL UNIQUE,
  description VARCHAR(200)
);

-- 2. BRANCHES
CREATE TABLE IF NOT EXISTS public.branches (
  branch_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_code VARCHAR(20) NOT NULL UNIQUE,
  branch_name VARCHAR(120) NOT NULL,
  address VARCHAR(500),
  contact_number VARCHAR(30),
  email VARCHAR(255),
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. USER_ACCOUNTS
CREATE TABLE IF NOT EXISTS public.user_accounts (
  user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_uid UUID UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
  role_id INT NOT NULL REFERENCES public.roles(role_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  branch_id INT REFERENCES public.branches(branch_id) ON DELETE SET NULL ON UPDATE CASCADE,
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
    CHECK (account_status IN ('ACTIVE', 'PENDING_VERIFICATION', 'SUSPENDED', 'LOCKED', 'INACTIVE')),
  email_verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. CUSTOMER_PROFILES
CREATE TABLE IF NOT EXISTS public.customer_profiles (
  customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL UNIQUE REFERENCES public.user_accounts(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
  first_name VARCHAR(80) NOT NULL,
  last_name VARCHAR(80) NOT NULL,
  phone VARCHAR(30),
  address VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- MODULE 2: SHOE BOOKING MANAGEMENT
-- ============================================================================

-- 5. BRANCH_HOURS
CREATE TABLE IF NOT EXISTS public.branch_hours (
  branch_hour_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id INT NOT NULL REFERENCES public.branches(branch_id) ON DELETE CASCADE ON UPDATE CASCADE,
  day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
  opening_time TIME,
  closing_time TIME,
  is_closed BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_branch_hours_day UNIQUE (branch_id, day_of_week)
);

-- 6. SHOE_SERVICES
CREATE TABLE IF NOT EXISTS public.shoe_services (
  service_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_name VARCHAR(120) NOT NULL UNIQUE,
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 7. BRANCH_SERVICES
CREATE TABLE IF NOT EXISTS public.branch_services (
  branch_service_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id INT NOT NULL REFERENCES public.branches(branch_id) ON DELETE CASCADE ON UPDATE CASCADE,
  service_id INT NOT NULL REFERENCES public.shoe_services(service_id) ON DELETE CASCADE ON UPDATE CASCADE,
  service_price DECIMAL(10,2) NOT NULL CHECK (service_price >= 0),
  estimated_duration_minutes INT NOT NULL DEFAULT 60 CHECK (estimated_duration_minutes > 0),
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_branch_service UNIQUE (branch_id, service_id)
);

-- 8. BOOKINGS
CREATE TABLE IF NOT EXISTS public.bookings (
  booking_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INT NOT NULL REFERENCES public.customer_profiles(customer_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  branch_service_id INT NOT NULL REFERENCES public.branch_services(branch_service_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  scheduled_at TIMESTAMPTZ NOT NULL,
  price_at_booking DECIMAL(10,2) NOT NULL CHECK (price_at_booking >= 0),
  booking_status VARCHAR(25) NOT NULL DEFAULT 'Confirmed'
    CHECK (booking_status IN ('Pending', 'Confirmed', 'Checked In', 'Completed', 'Cancelled', 'Rescheduled')),
  customer_request TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- MODULE 4: ORDER MANAGEMENT
-- ============================================================================

-- 9. SERVICE_ORDERS
CREATE TABLE IF NOT EXISTS public.service_orders (
  order_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INT NOT NULL UNIQUE REFERENCES public.bookings(booking_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  order_number VARCHAR(40) NOT NULL UNIQUE,
  received_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  assigned_to_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  received_at TIMESTAMPTZ DEFAULT NOW(),
  assigned_at TIMESTAMPTZ,
  assignment_accepted_at TIMESTAMPTZ,
  assignment_status VARCHAR(25) NOT NULL DEFAULT 'Assigned'
    CHECK (assignment_status IN ('Unassigned', 'Assigned', 'Accepted', 'In Work', 'Completed')),
  due_at TIMESTAMPTZ,
  order_status VARCHAR(25) NOT NULL DEFAULT 'Pending Assessment'
    CHECK (order_status IN ('Pending Assessment', 'In Progress', 'Quality Check', 'Ready for Pickup', 'Completed')),
  work_instructions TEXT,
  progress_notes TEXT,
  completed_at TIMESTAMPTZ
);

-- ============================================================================
-- MODULE 6: ASSESSMENT AND DOCUMENTATION
-- ============================================================================

-- 10. SHOE_ASSESSMENTS
CREATE TABLE IF NOT EXISTS public.shoe_assessments (
  assessment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INT NOT NULL UNIQUE REFERENCES public.service_orders(order_id) ON DELETE CASCADE ON UPDATE CASCADE,
  assessed_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  shoe_condition TEXT,
  damage_findings TEXT,
  recommendations TEXT,
  service_notes TEXT,
  assessment_status VARCHAR(25) NOT NULL DEFAULT 'Pending'
    CHECK (assessment_status IN ('Pending', 'Draft', 'Completed', 'Approved')),
  assessed_at TIMESTAMPTZ DEFAULT NOW(),
  finalized_at TIMESTAMPTZ
);

-- 11. ASSESSMENT_PHOTOS
CREATE TABLE IF NOT EXISTS public.assessment_photos (
  photo_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id INT NOT NULL REFERENCES public.shoe_assessments(assessment_id) ON DELETE CASCADE ON UPDATE CASCADE,
  uploaded_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  photo_type VARCHAR(20) NOT NULL
    CHECK (photo_type IN (
      'BEFORE', 'AFTER',
      'BEFORE_LEFT', 'BEFORE_RIGHT', 'BEFORE_TOE', 'BEFORE_SOLE',
      'AFTER_LEFT', 'AFTER_RIGHT', 'AFTER_TOE', 'AFTER_SOLE'
    )),
  file_path VARCHAR(500) NOT NULL,
  caption VARCHAR(255),
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- MODULE 3: CUSTOMER RELATIONSHIP MANAGEMENT (CRM)
-- ============================================================================

-- 12. CRM_INTERACTIONS
CREATE TABLE IF NOT EXISTS public.crm_interactions (
  interaction_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INT NOT NULL REFERENCES public.customer_profiles(customer_id) ON DELETE CASCADE ON UPDATE CASCADE,
  handled_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  interaction_type VARCHAR(25) NOT NULL
    CHECK (interaction_type IN ('REVIEW', 'INQUIRY', 'COMPLAINT', 'FOLLOW_UP', 'FEEDBACK')),
  customer_message TEXT,
  staff_response TEXT,
  rating SMALLINT CHECK (rating IS NULL OR (rating BETWEEN 1 AND 5)),
  interaction_status VARCHAR(25) NOT NULL DEFAULT 'Open'
    CHECK (interaction_status IN ('Open', 'In Review', 'Responded', 'Published', 'Closed')),
  interaction_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  responded_at TIMESTAMPTZ
);

-- 13. NOTIFICATIONS
CREATE TABLE IF NOT EXISTS public.notifications (
  notification_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INT NOT NULL REFERENCES public.customer_profiles(customer_id) ON DELETE CASCADE ON UPDATE CASCADE,
  notification_type VARCHAR(30) NOT NULL
    CHECK (notification_type IN (
      'BOOKING_CONFIRMATION',
      'BOOKING_UPDATE',
      'ORDER_STATUS_UPDATE',
      'READY_FOR_PICKUP',
      'ORDER_COMPLETED',
      'ASSESSMENT_UPDATE',
      'SYSTEM_ALERT'
    )),
  message TEXT NOT NULL,
  delivery_status VARCHAR(20) NOT NULL DEFAULT 'Pending'
    CHECK (delivery_status IN ('Pending', 'Sent', 'Delivered', 'Read', 'Failed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  sent_at TIMESTAMPTZ,
  read_at TIMESTAMPTZ
);

-- 14. NOTIFICATION_CONTEXTS
CREATE TABLE IF NOT EXISTS public.notification_contexts (
  notification_id INT PRIMARY KEY REFERENCES public.notifications(notification_id) ON DELETE CASCADE ON UPDATE CASCADE,
  booking_id INT REFERENCES public.bookings(booking_id) ON DELETE SET NULL ON UPDATE CASCADE,
  order_id INT REFERENCES public.service_orders(order_id) ON DELETE SET NULL ON UPDATE CASCADE
);

-- 15. CUSTOMER_NOTIFICATION_PREFERENCES
CREATE TABLE IF NOT EXISTS public.customer_notification_preferences (
  preference_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INT NOT NULL REFERENCES public.customer_profiles(customer_id) ON DELETE CASCADE ON UPDATE CASCADE,
  preference_type VARCHAR(40) NOT NULL,
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_customer_preference UNIQUE (customer_id, preference_type)
);

-- ============================================================================
-- MODULE 5: INVENTORY MANAGEMENT
-- ============================================================================

-- 16. SUPPLIERS
CREATE TABLE IF NOT EXISTS public.suppliers (
  supplier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_name VARCHAR(150) NOT NULL,
  contact_person VARCHAR(120),
  phone VARCHAR(30),
  email VARCHAR(255),
  address VARCHAR(500),
  supplier_status VARCHAR(20) NOT NULL DEFAULT 'Active'
    CHECK (supplier_status IN ('Active', 'Inactive', 'Suspended'))
);

-- 17. INVENTORY_ITEMS
CREATE TABLE IF NOT EXISTS public.inventory_items (
  item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_code VARCHAR(40) NOT NULL UNIQUE,
  item_name VARCHAR(120) NOT NULL,
  category VARCHAR(60) NOT NULL,
  unit_of_measure VARCHAR(20) NOT NULL DEFAULT 'units',
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 18. PURCHASE_ORDERS
CREATE TABLE IF NOT EXISTS public.purchase_orders (
  purchase_order_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id INT NOT NULL REFERENCES public.suppliers(supplier_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  branch_id INT NOT NULL REFERENCES public.branches(branch_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  requested_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  approved_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  supplier_quote_reference VARCHAR(80),
  order_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  purchase_status VARCHAR(25) NOT NULL DEFAULT 'Pending'
    CHECK (purchase_status IN ('Draft', 'Pending', 'Approved', 'Ordered', 'Partially Received', 'Received', 'Cancelled')),
  notes TEXT,
  approved_at TIMESTAMPTZ
);

-- 19. PURCHASE_ORDER_ITEMS
CREATE TABLE IF NOT EXISTS public.purchase_order_items (
  purchase_order_item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id INT NOT NULL REFERENCES public.purchase_orders(purchase_order_id) ON DELETE CASCADE ON UPDATE CASCADE,
  item_id INT NOT NULL REFERENCES public.inventory_items(item_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  quantity_requested DECIMAL(12,2) NOT NULL CHECK (quantity_requested > 0),
  quoted_unit_cost DECIMAL(10,2) NOT NULL DEFAULT 0.00 CHECK (quoted_unit_cost >= 0)
);

-- 20. DELIVERIES
CREATE TABLE IF NOT EXISTS public.deliveries (
  delivery_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id INT NOT NULL REFERENCES public.purchase_orders(purchase_order_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  received_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  delivery_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  proof_of_delivery_path VARCHAR(500),
  delivery_status VARCHAR(25) NOT NULL DEFAULT 'Received'
    CHECK (delivery_status IN ('Pending', 'Partial', 'Received', 'Inspecting', 'Rejected')),
  delivery_notes TEXT
);

-- 21. DELIVERY_ITEMS
CREATE TABLE IF NOT EXISTS public.delivery_items (
  delivery_item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_id INT NOT NULL REFERENCES public.deliveries(delivery_id) ON DELETE CASCADE ON UPDATE CASCADE,
  purchase_order_item_id INT NOT NULL REFERENCES public.purchase_order_items(purchase_order_item_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  quantity_received DECIMAL(12,2) NOT NULL CHECK (quantity_received >= 0)
);

-- 22. BRANCH_INVENTORY
CREATE TABLE IF NOT EXISTS public.branch_inventory (
  branch_inventory_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id INT NOT NULL REFERENCES public.branches(branch_id) ON DELETE CASCADE ON UPDATE CASCADE,
  item_id INT NOT NULL REFERENCES public.inventory_items(item_id) ON DELETE CASCADE ON UPDATE CASCADE,
  reorder_level DECIMAL(12,2) NOT NULL DEFAULT 10.00 CHECK (reorder_level >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_branch_inventory_item UNIQUE (branch_id, item_id)
);

-- 23. STOCK_MOVEMENTS
CREATE TABLE IF NOT EXISTS public.stock_movements (
  movement_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_inventory_id INT NOT NULL REFERENCES public.branch_inventory(branch_inventory_id) ON DELETE CASCADE ON UPDATE CASCADE,
  order_id INT REFERENCES public.service_orders(order_id) ON DELETE SET NULL ON UPDATE CASCADE,
  recorded_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  movement_type VARCHAR(25) NOT NULL
    CHECK (movement_type IN ('RESTOCK', 'DELIVERY', 'USAGE', 'TRANSFER_IN', 'TRANSFER_OUT', 'ADJUSTMENT', 'RETURN')),
  quantity_change DECIMAL(12,2) NOT NULL,
  transfer_reference VARCHAR(40),
  movement_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  notes VARCHAR(500)
);

-- 24. SUPPLIER_RETURNS
CREATE TABLE IF NOT EXISTS public.supplier_returns (
  supplier_return_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_item_id INT NOT NULL REFERENCES public.delivery_items(delivery_item_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  quantity_returned DECIMAL(12,2) NOT NULL CHECK (quantity_returned > 0),
  reason TEXT,
  supplier_response TEXT,
  refund_amount DECIMAL(10,2) NOT NULL DEFAULT 0.00 CHECK (refund_amount >= 0),
  return_status VARCHAR(25) NOT NULL DEFAULT 'Requested'
    CHECK (return_status IN ('Requested', 'Approved', 'Replaced', 'Refunded', 'Rejected')),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_at TIMESTAMPTZ
);

-- ============================================================================
-- MODULE 7: ADMINISTRATION DASHBOARD
-- ============================================================================

-- 25. AUDIT_LOGS
CREATE TABLE IF NOT EXISTS public.audit_logs (
  audit_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  module_name VARCHAR(60) NOT NULL,
  action_type VARCHAR(40) NOT NULL,
  target_entity VARCHAR(60) NOT NULL,
  target_record_id INT,
  details TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 26. SYSTEM_SETTINGS
CREATE TABLE IF NOT EXISTS public.system_settings (
  setting_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_key VARCHAR(100) NOT NULL UNIQUE,
  setting_value TEXT,
  updated_by_user_id INT REFERENCES public.user_accounts(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Security Support Table for Brute-Force Protection & Rate Limiting
CREATE TABLE IF NOT EXISTS public.security_login_attempts (
  attempt_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  ip_address VARCHAR(64),
  was_successful BOOLEAN NOT NULL DEFAULT FALSE,
  attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
