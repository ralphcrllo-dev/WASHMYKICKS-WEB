-- 1. ROLES
CREATE TABLE IF NOT EXISTS public.roles (
  role_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(30) NOT NULL UNIQUE,
  description VARCHAR(200)
);

-- 2. BRANCHES
CREATE TABLE IF NOT EXISTS public.branches (
  branch_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_code VARCHAR(20) NOT NULL UNIQUE,
  branch_name VARCHAR(120) NOT NULL,
  address VARCHAR(500),
  contact_number VARCHAR(30),
  email VARCHAR(255),
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. USER_ACCOUNTS
CREATE TABLE IF NOT EXISTS public.user_accounts (
  user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_uid UUID UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
  role_id INT NOT NULL REFERENCES public.roles(role_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  branch_id INT REFERENCES public.branches(branch_id) ON DELETE SET NULL ON UPDATE CASCADE,
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
    CHECK (account_status IN ('ACTIVE', 'PENDING_VERIFICATION', 'SUSPENDED', 'LOCKED', 'INACTIVE')),
  email_verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. CUSTOMER_PROFILES
CREATE TABLE IF NOT EXISTS public.customer_profiles (
  customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL UNIQUE REFERENCES public.user_accounts(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
  first_name VARCHAR(80) NOT NULL,
  last_name VARCHAR(80) NOT NULL,
  phone VARCHAR(30),
  address VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

