    AND public.fn_is_admin()
  )
  WITH CHECK (
    bucket_id IN ('before-photos', 'after-photos')
    AND public.fn_is_admin()
  );

-- Staff: Read, upload, and update photos for their assigned branch
DROP POLICY IF EXISTS "storage_staff_branch_photos_select" ON storage.objects;
